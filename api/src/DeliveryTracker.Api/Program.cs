using DeliveryTracker.Application;
using DeliveryTracker.Infrastructure;
using Serilog;

// Bootstrap logger: catches errors that happen before the app is fully configured.
// It is replaced by the real logger (read from appsettings.json) once the host starts.
Log.Logger = new LoggerConfiguration()
    .WriteTo.Console()
    .CreateBootstrapLogger();

try
{
    var builder = WebApplication.CreateBuilder(args);

    // Serilog replaces the default .NET logging; settings come from the "Serilog" section.
    builder.Services.AddSerilog((services, config) => config
        .ReadFrom.Configuration(builder.Configuration)
        .ReadFrom.Services(services));

    // Each layer registers its own services.
    builder.Services
        .AddApplication()
        .AddInfrastructure(builder.Configuration);

    builder.Services.AddControllers();
    builder.Services.AddOpenApi();      // built-in generator: /openapi/v1.json
    builder.Services.AddHealthChecks(); // later: .AddNpgSql(...) to also check the database

    var app = builder.Build();

    // One clean log line per HTTP request (method, path, status code, duration).
    app.UseSerilogRequestLogging();

    if (app.Environment.IsDevelopment())
    {
        app.MapOpenApi();
        // Swagger UI at /swagger, reading the document generated by .NET.
        app.UseSwaggerUI(options =>
            options.SwaggerEndpoint("/openapi/v1.json", "DeliveryTracker API v1"));
    }

    app.UseHttpsRedirection();

    app.UseAuthorization();

    app.MapControllers();
    app.MapHealthChecks("/health");

    app.Run();
}
catch (Exception ex)
{
    Log.Fatal(ex, "Application terminated unexpectedly");
}
finally
{
    Log.CloseAndFlush();
}
